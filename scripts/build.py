#!/usr/bin/env python3
"""Build the Contract Portal: assemble index.html from the layered sources.

Reads:
  src/template.html   HTML shell with {{...}} placeholders
  src/analytics.html  Vercel analytics scripts (injected byte-for-byte)
  src/styles.css      portal CSS
  src/app.js          app logic (reads JOBS / EXPIRED from window.PORTAL_DATA)
  data/roles.json     roles, expired stamps, snapshot, totals

Writes:
  index.html          generated page — do not hand-edit

Usage:  python3 scripts/build.py        (from the repo root)
Requires: Python 3, standard library only. Output is deterministic:
same inputs always produce the same index.html.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

GENERATED_COMMENT = (
    "<!-- GENERATED by scripts/build.py — do not hand-edit. "
    "Edit src/ and data/roles.json, then run: python3 scripts/build.py -->"
)

SNAPSHOT_RE = re.compile(r"^(.+?\d{4}), \d{1,2}(?::\d{2})?[ap]m ET$")


def dump_job(job):
    """One job per line, keys in roles.json order, no spaces (matches the
    original single-file formatting, apart from quoted keys)."""
    return json.dumps(job, ensure_ascii=False, separators=(",", ":"))


def main():
    template = (ROOT / "src" / "template.html").read_text(encoding="utf-8")
    analytics = (ROOT / "src" / "analytics.html").read_text(encoding="utf-8")
    styles = (ROOT / "src" / "styles.css").read_text(encoding="utf-8")
    app_js = (ROOT / "src" / "app.js").read_text(encoding="utf-8")
    roles = json.loads((ROOT / "data" / "roles.json").read_text(encoding="utf-8"))

    snapshot = roles["snapshot"]
    totals = roles["totals"]
    jobs = roles["jobs"]
    expired = roles["expired"]

    # --- validate the data before emitting anything ---
    m = SNAPSHOT_RE.match(snapshot)
    if not m:
        sys.exit("error: snapshot %r does not look like 'Nov 23, 2026, 4pm ET'" % snapshot)
    snapshot_date = m.group(1)
    ids = [j["id"] for j in jobs]
    if len(ids) != len(set(ids)):
        sys.exit("error: duplicate job ids in data/roles.json")
    if len(jobs) != totals["total"]:
        sys.exit("error: totals.total=%s but roles.json has %s jobs"
                 % (totals["total"], len(jobs)))
    if len(expired) != totals["expired"]:
        sys.exit("error: totals.expired=%s but roles.json has %s expired entries"
                 % (totals["expired"], len(expired)))
    live = sum(1 for j in jobs if str(j["id"]) not in expired)
    if live != totals["live"]:
        sys.exit("error: totals.live=%s but %s jobs are not expired"
                 % (totals["live"], live))
    unknown = [k for k in expired if int(k) not in set(ids)]
    if unknown:
        sys.exit("error: expired entries with no matching job: %s" % unknown)
    for j in jobs:
        for field in ("id", "title", "company", "url", "postedISO"):
            if field not in j:
                sys.exit("error: job %s is missing %r" % (j.get("id"), field))
    h1b_live = sum(1 for j in jobs if j.get("h1b") and str(j["id"]) not in expired)

    # --- data block injected into the main <script> ---
    data_lines = [
        "window.PORTAL_DATA = {\"snapshot\": " + json.dumps(snapshot, ensure_ascii=False)
        + ", \"totals\": " + json.dumps(totals, ensure_ascii=False, separators=(",", ":"))
        + ", \"jobs\": [",
    ]
    for i, job in enumerate(jobs):
        data_lines.append(dump_job(job) + ("," if i < len(jobs) - 1 else ""))
    data_lines.append(
        "], \"expired\": " + json.dumps(expired, ensure_ascii=False, separators=(",", ":")) + "};"
    )
    data_lines.append("var JOBS = window.PORTAL_DATA.jobs;")
    data_lines.append("var EXPIRED = window.PORTAL_DATA.expired;")
    data_block = "\n".join(data_lines) + "\n"
    if "</script" in data_block.lower() or "<!--" in data_block:
        sys.exit("error: role data contains a string that would break the inline <script>")

    # --- assemble ---
    for token in ("{{ANALYTICS}}", "{{STYLES}}", "{{ROLES_DATA}}", "{{APP_JS}}",
                  "{{LIVE}}", "{{EXPIRED}}", "{{TOTAL}}", "{{H1B}}",
                  "{{SNAPSHOT}}", "{{SNAPSHOT_DATE}}"):
        if token not in template:
            sys.exit("error: placeholder %s missing from src/template.html" % token)

    html = template
    html = html.replace("{{LIVE}}", str(live))
    html = html.replace("{{EXPIRED}}", str(len(expired)))
    html = html.replace("{{TOTAL}}", str(len(jobs)))
    html = html.replace("{{H1B}}", str(h1b_live))
    html = html.replace("{{SNAPSHOT}}", snapshot)
    html = html.replace("{{SNAPSHOT_DATE}}", snapshot_date)
    html = html.replace("<!-- {{ANALYTICS}} -->\n", analytics)
    html = html.replace("<!-- {{STYLES}} -->\n", styles)
    html = html.replace("<!-- {{ROLES_DATA}} -->\n", data_block)
    html = html.replace("<!-- {{APP_JS}} -->\n", app_js)

    if "{{" in html:
        sys.exit("error: unreplaced placeholder left in output")

    out = ROOT / "index.html"
    out.write_text(GENERATED_COMMENT + "\n" + html, encoding="utf-8")
    print("built %s (%d bytes): %d jobs, %d live, %d expired, %d H-1B live, snapshot %s"
          % (out, out.stat().st_size, len(jobs), live, len(expired), h1b_live, snapshot))


if __name__ == "__main__":
    main()
